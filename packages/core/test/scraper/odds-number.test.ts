import { describe, expect, it } from "vitest";
import { toOddsNumber } from "../../src/scraper/odds-number.js";

/**
 * 共有ヘルパ `toOddsNumber`(Issue #73)の直接テスト。
 * 単勝・複勝(中央)・ワイド/3連複(中央・地方)・地方単複の5経路すべてが本ヘルパに委譲するため、
 * ここで契約を1箇所に固定する。値域(1.0以上・0の排除)は課さない(#23/#74で決定)。
 */
describe("toOddsNumber(オッズ文字列の数値化。Issue #73)", () => {
  // 条件A0: すべて `toBe` で値として比較する(述語検査は使わない)。
  // 条件A': 期待値列に受理(数値)と拒否(null)の両方が含まれる。
  // 条件B: 入力列と期待値列のベクトルが全行を通じて一致しない。
  it.each<[unknown, number | null, string]>([
    // --- 受理 ---
    ["1.5", 1.5, "プレーンな小数はそのまま数値化される"],
    [" 1.5 ", 1.5, "前後空白はtrimしてから数値化する"],
    ["1,234.5", 1234.5, "3桁区切りカンマを1つ含む小数はカンマを除去して数値化される"],
    ["1,234", 1234, "3桁区切りカンマを1つ含む整数はカンマを除去して数値化される"],
    ["1,234,567.8", 1234567.8, "3桁区切りカンマを複数含む小数もすべて除去して数値化される"],
    ["999.9", 999.9, "3桁未満(カンマなし)の小数はそのまま数値化される"],
    ["0", 0, "値域(1.0以上・0の排除)は課さないため\"0\"はそのまま0になる"],
    // --- 拒否(null) ---
    ["", null, "空文字は非数値のためnull"],
    ["---.-", null, "未確定表記はnull"],
    ["取消", null, "出走取消表記はnull"],
    ["1,23.4", null, "区切り位置が3桁ごとでない(2桁)ためnull"],
    ["1,2345", null, "区切り位置が3桁ごとでない(4桁)ためnull"],
    [",123", null, "先頭がカンマのためnull"],
    ["1,", null, "末尾がカンマのためnull"],
    ["1 234.5", null, "カンマではなくスペース区切りのためnull"],
    ["１,２３４.５", null, "全角数字・全角カンマはnull"],
    ["1e3", null, "指数表記はnull"],
    ["+1.5", null, "先頭の符号(+)はnull"],
    ["-1.5", null, "先頭の符号(-)はnull"],
    [".5", null, "整数部を欠く小数表記はnull"],
    ["1.", null, "小数部を欠く小数点付き表記はnull"],
    // --- 非文字列 ---
    [null, null, "nullはnull"],
    [undefined, null, "undefinedはnull"],
    [123, null, "数値型そのもの(文字列でない)はnull"],
    [["1.5"], null, "配列(非文字列)はnull"],
  ])("入力 %j は %j になること(%s)", (raw, expected) => {
    expect(toOddsNumber(raw)).toBe(expected);
  });
});
