/** バイアス重み7項目(core の BiasWeights と構造一致。このファイルを core非依存に保つため再定義)。 */
export interface BiasWeightValues {
  /** 馬場状態適性(道悪)。 */
  readonly trackCondition: number;
  /** 競馬場適性。 */
  readonly venue: number;
  /** 季節適性。 */
  readonly season: number;
  /** 枠順適性(馬個別)。 */
  readonly frame: number;
  /** 夏負けフラグ。 */
  readonly summerFatigue: number;
  /** 輸送・滞在バイアス。 */
  readonly transport: number;
  /** ローテーション適性。 */
  readonly rotation: number;
}

/** 基礎スコア重み8項目(core の BaseScoreWeights と構造一致。7 つ目の timeIndex は Issue #353、8 つ目の trainer は Issue #354 で足した)。 */
export interface BaseScoreWeightValues {
  /** 近走着順(重み減衰付き)。 */
  readonly recentForm: number;
  /** 上がり3F水準。 */
  readonly last3f: number;
  /** コース・距離適性。 */
  readonly courseDistance: number;
  /** 騎手の当該コース複勝率。 */
  readonly jockey: number;
  /** 斤量変化(キー名は「斤量・馬体重」だった頃のまま据え置き。馬体重の減点は Issue #213 で撤去)。 */
  readonly weightChange: number;
  /** コースレベル枠順バイアス。 */
  readonly courseFrameBias: number;
  /** タイム指数(Issue #353)。 */
  readonly timeIndex: number;
  /** 調教師の前2年の3着内率(Issue #354)。 */
  readonly trainer: number;
}

