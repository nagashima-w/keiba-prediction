/**
 * オッズ文字列の数値化を担う共有ヘルパ(Issue #73)。
 *
 * ## なぜ共有するのか
 * 単勝・複勝(`parse-odds.ts`)/ワイド・3連複(`parse-combo-odds.ts`・`parse-nar-combo-odds.ts`)/
 * 地方単複(`parse-nar-odds.ts`)は、いずれもオッズ文字列を数値化する `toOddsNumber`
 * (または `toWinOddsNumber`)を個別に実装していた。ところが `parse-odds.ts`・
 * `parse-nar-odds.ts` の2本だけが**桁区切りカンマに非対応**であり、`parse-combo-odds.ts`・
 * `parse-nar-combo-odds.ts` は #32 でカンマ対応済みだった。**同一概念・同名の関数が
 * 同一リポジトリ内で異なる契約を持つ状態**(`scraper/ninki.ts` が #34 で是正した構図と同型)
 * であり、しかもカンマが現れるのは1,000倍以上の高オッズだけのため、**取りこぼしが
 * ランダムではなく高オッズ側(妙味の源泉)に系統的に偏る**という実害があった
 * (`parse-combo-odds.ts` の実測: 3連複560件中251件がカンマ入り)。
 * そのため実装を本モジュール1本に統合する。
 *
 * ## 契約
 * - 非文字列(数値・`null`・`undefined`・配列等) → `null`
 * - 前後空白を trim した結果が `/^[0-9]+(\.[0-9]+)?$/`(プレーンな数値表記) → `Number`化
 * - trim した結果が `/^[0-9]{1,3}(,[0-9]{3})*(\.[0-9]+)?$/`
 *   (3桁ごとの桁区切りカンマを持つ数値表記) → カンマを除去してから `Number`化
 * - それ以外 → `null`
 *
 * 上記いずれのパターンにも一致しない具体例(すべて `null`):
 * - 全角カンマ・全角数字(例: `"１,２３４.５"`)。半角の数字・カンマのみを受理する
 * - スペース区切り(例: `"1 234.5"`)。区切り文字はカンマのみを受理する
 * - 不正な区切り位置(例: `"1,23.4"` 2桁区切り、`"1,2345"` 4桁区切り、`",123"` 先頭カンマ、
 *   `"1,"` 末尾カンマ)。3桁ごとの区切りのみを受理する
 * - 指数表記(`"1e3"`)・符号付き(`"+1.5"`・`"-1.5"`)・整数部/小数部を欠く小数点表記
 *   (`".5"`・`"1."`)
 *
 * ## 引数型を `unknown` にする理由(#34の裁定を踏襲)
 * `string` に狭めると、呼び出し側で必ず `typeof` 判定が挟まることになり、本ヘルパの
 * 非文字列分岐(1行目の `typeof raw !== "string"` 判定)が呼び出し側からは到達不能な
 * 死にコードになる。`unknown` のまま受け取ることで、この分岐自体をテーブル駆動テストで
 * 直接検証できる(`odds-number.test.ts`)。
 *
 * ## 値域(1.0以上・0の排除)は課さない
 * 本ヘルパは「文字列として妥当な数値表記か」だけを判定し、オッズとして意味のある
 * 値域(1.0以上)であるかどうかは判定しない(`"0"` はそのまま `0` を返す)。
 * 値域の保証をパース側(生成側)で行うか、EV計算側(`ev/expected-value.ts`)で行うかは
 * **#23 の着手前ゲートで決める**(#74「オッズ0の値域外通過」関連)。本モジュールが
 * 「決めていない」ことを明示するのであって、この状態が恒久であると宣言するものではない。
 */

const PLAIN_NUMBER = /^[0-9]+(\.[0-9]+)?$/;
/** 桁区切りカンマ付き数値(例: "1,234.5")。3桁ごとの区切りのみ許容し、不正な区切りは拒否する。 */
const GROUPED_NUMBER = /^[0-9]{1,3}(,[0-9]{3})*(\.[0-9]+)?$/;

/**
 * オッズ文字列を数値化する。非数値・未確定("---.-"等)は null。
 * 桁区切りカンマ(3桁ごと)を許容する。値域(1.0以上・0の排除)は課さない(モジュールJSDoc参照)。
 */
export function toOddsNumber(raw: unknown): number | null {
  if (typeof raw !== "string") {
    return null;
  }
  const trimmed = raw.trim();
  if (PLAIN_NUMBER.test(trimmed)) {
    return Number(trimmed);
  }
  if (GROUPED_NUMBER.test(trimmed)) {
    return Number(trimmed.replace(/,/g, ""));
  }
  return null;
}
