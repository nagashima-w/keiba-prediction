/**
 * nar-trio-axis — 地方(NAR)3連複の軸馬別取得(#33)で叩くべき軸馬番の集合を導出する葉モジュール。
 *
 * ## 契約(Issue #33本文の⚠️「重要な境界値」。boss着手前ゲートで確定)
 *
 * `narTrioOddsPageUrl` のJSDoc(#13の実測)が示す性質「`jiku=k` は k を含む全トリオを返す」
 * から、「S(出走馬番集合)の任意の3部分集合が軸集合Aと交わるには `|S\A| ≤ 2`、すなわち
 * `|A| ≥ n-2`(Aはどのn-2個でもよい)」が成り立つ。**「軸馬番の値がn-2以下」ではない。**
 *
 * #13時点の「軸1〜n-2」という表現は、出走馬番が1..nの連番であることを暗黙に仮定していた。
 * 取消等で馬番が飛ぶ(非連番の)場合、リテラルに「軸1〜3」を叩くと出走していない馬番を
 * 軸に指定することになり破綻する(例: 出走馬番`{2,3,5,7,9}`には馬番1が存在しない)。
 *
 * 本モジュールは「出走馬番を昇順に並べた先頭 n-2 頭を軸にする」という正しい命題を実装する。
 *
 * ## 網羅性(導出値。`nar-trio-axis.test.ts`で小さいnについて実際に列挙して検証済み)
 *
 * 軸集合A(|A|=n-2)について「Aの各要素kが返す『kを含む全トリオ』」の和集合が
 * 全トリオC(n,3)と完全一致することは、上記の命題(`|S\A|≤2`)から従う導出値であり、
 * 実測値ではない(#13が実測したのは「jiku=kがkを含む全トリオを返す」という個別の性質のみ)。
 */

/**
 * 出走馬番の集合(順不同・重複ありうる)から、地方3連複の軸馬別取得で叩くべき軸馬番の
 * 配列を導出する。
 *
 * 契約: 重複を排除し昇順に整列した上で、先頭 `n-2`(nは重複排除後の頭数)を軸として返す。
 * `n<3` の場合は軸0件(空配列)を返す(3頭未満では3連複の組合せ自体が成立しないため)。
 *
 * @param startingUmabans 出走馬番の集合(順不同・重複ありうる)
 * @returns 軸馬番の配列(昇順。n<3のときは空配列)
 */
export function deriveNarTrioAxisUmabans(startingUmabans: readonly number[]): number[] {
  const uniqueSorted = [...new Set(startingUmabans)].sort((a, b) => a - b);
  const axisCount = Math.max(0, uniqueSorted.length - 2);
  return uniqueSorted.slice(0, axisCount);
}
