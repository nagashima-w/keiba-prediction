/**
 * 回収率の表示(Issue #245)。**依存を持たない純モジュール**: Worker(Discord の日報・LLM のプロンプト)と、ブラウザのクライアント(日報の画面)の両方が import する。
 *
 * 小数第 1 位に丸めると「100.0%」になる値(0.9995 以上 1 未満、または 1 を超え 1.0005 未満)は、**実際には 1 ちょうどではない**(赤字・黒字)。
 * 「100.0%(赤字)」のように表示と判定が矛盾して見えるので、**「100.0%」と出すのは rate === 1 のときだけ**にする:
 *  - 1 未満で丸めると 100.0% になる値は、小数 2 桁で出し、上限を 99.99% にする(0.99995 以上は 2 桁に丸めても 100.00 になるため)。
 *  - 1 超で丸めると 100.0% になる値は、小数 2 桁で出し、下限を 100.01% にする(1.00005 未満は 2 桁に丸めても 100.00 になるため)。
 * それ以外は従来どおりの小数第 1 位(exe の検証画面の `formatRate` と同じ出力)。
 *
 * 判定は数値の閾値ではなく**丸めた文字列**で行う(0.9995 の `toFixed(1)` は浮動小数の都合で "100.0" になる。数値の閾値を別に持つと、この境界がずれうる)。
 * 表示だけを変える関数で、色・「赤字/黒字/収支±0」の語の判定(`recoveryRate >= 1` など)は元の値で行う。
 */
export function formatRecoveryPercent(rate: number): string {
  const oneDecimal = (rate * 100).toFixed(1);
  if (!Number.isFinite(rate) || rate === 1 || oneDecimal !== "100.0") {
    return `${oneDecimal}%`;
  }
  // 1 未満は 99.99 を上限に、1 超は 100.01 を下限に(百分率の 0.01 刻み = rate × 10000 の整数)。
  const hundredths = rate < 1 ? Math.min(Math.round(rate * 10000), 9999) : Math.max(Math.round(rate * 10000), 10001);
  return `${(hundredths / 100).toFixed(2)}%`;
}
