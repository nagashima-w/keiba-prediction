--     ・3連単(JRA の頁は 1 本で取れる)は足していない。要るなら別段階(14 頭で約 35KB、18 頭で約 80KB と見込む)。
--   JRA の頁が空きにしている組(自分自身との組・1 頭だけの枠の同枠)はキーを作らない。2 頭以上の枠の同枠(例: "0303")は残る。
